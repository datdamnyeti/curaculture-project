-- CuraCulture: the survey link loop on instrument v2.1
--
-- The anonymity firewall is structural:
--   * invitations know WHO was asked and whether they finished (status only);
--   * responses know WHAT was answered;
--   * nothing joins the two. responses has no token, no invitation id, no
--     employee id and no timestamp, so nothing in the data matches an answer
--     to a person. (Anyone watching the live database as people submit could
--     still correlate timing; that is an operational control, not a schema one.)
-- Raw survey tokens are never stored. The server derives each token from the
-- invitation id with a secret (HMAC) and stores only a SHA-256 hash for lookup.
--
-- Staff never authenticate. Every survey read and write goes through the
-- security-definer functions below, which only the service role may call.

-- gen_random_uuid() is built into Postgres 13+; tokens are hashed by the server.

-- ---------------------------------------------------------------- clinics
create table public.clinics (
  id               uuid primary key default gen_random_uuid(),
  name             text not null check (length(trim(name)) > 0),
  team_size        integer check (team_size is null or team_size > 0),
  clinic_type      text,
  ownership        text,
  hours            text,
  -- open decision from the v2.1 brief: what staff are promised on the intro page
  survey_intro     text not null default 'researcher' check (survey_intro in ('researcher', 'selfserve')),
  -- written answers: researcher screens and owners see approved quotes, or owners never see them
  open_ended_mode  text not null default 'screened' check (open_ended_mode in ('screened', 'hidden')),
  created_at       timestamptz not null default now()
);

create table public.clinic_members (
  clinic_id  uuid not null references public.clinics (id) on delete cascade,
  user_id    uuid not null references auth.users (id) on delete cascade,
  role       text not null check (role in ('owner', 'admin', 'viewer', 'researcher')),
  created_at timestamptz not null default now(),
  primary key (clinic_id, user_id)
);
create index clinic_members_user_idx on public.clinic_members (user_id);

-- ---------------------------------------------------------------- roster
-- Contact details are used only to send links and to count headcount.
-- Analysis never uses the roster role; staff self-report D1 in the survey.
create table public.employees (
  id         uuid primary key default gen_random_uuid(),
  clinic_id  uuid not null references public.clinics (id) on delete cascade,
  name       text not null check (length(trim(name)) > 0),
  email      text,
  phone      text,
  role_code  smallint check (role_code between 1 and 8),
  active     boolean not null default true,
  created_at timestamptz not null default now()
);
create index employees_clinic_idx on public.employees (clinic_id) where active;

-- ---------------------------------------------------------------- campaigns
create table public.campaigns (
  id                 uuid primary key default gen_random_uuid(),
  clinic_id          uuid not null references public.clinics (id) on delete cascade,
  name               text not null,
  instrument_version text not null,
  kind               text not null default 'full' check (kind in ('full', 'pulse')),
  status             text not null default 'active' check (status in ('active', 'closed')),
  opens_on           date not null default current_date,
  closes_on          date not null,
  created_by         uuid references auth.users (id) on delete set null,
  created_at         timestamptz not null default now(),
  check (closes_on >= opens_on)
);
create index campaigns_clinic_idx on public.campaigns (clinic_id);

-- ---------------------------------------------------------------- invitations
create table public.invitations (
  id             uuid primary key,                       -- generated by the server; the link is derived from it
  campaign_id    uuid not null references public.campaigns (id) on delete cascade,
  employee_id    uuid references public.employees (id) on delete set null,
  token_hash     text not null unique,                   -- sha256(token), hex
  channel        text not null check (channel in ('email', 'text')),
  status         text not null default 'not_started' check (status in ('not_started', 'in_progress', 'complete')),
  draft          jsonb,                                  -- held only while in progress; deleted on submit
  reminders_sent integer not null default 0
  -- deliberately no completed_at: a timestamp here and an insert order there
  -- would let someone match an invitation to a response.
);
create index invitations_campaign_idx on public.invitations (campaign_id);

-- ---------------------------------------------------------------- responses
create table public.responses (
  id                 uuid primary key default gen_random_uuid(),
  clinic_id          uuid not null references public.clinics (id) on delete cascade,
  campaign_id        uuid not null references public.campaigns (id) on delete cascade,
  instrument_version text not null,
  demographics       jsonb not null default '{}'::jsonb,  -- { "D1": 3, "D1_other": "...", ... }
  answers            jsonb not null default '{}'::jsonb,  -- raw codes by item id, reverse items NOT recoded
  open_ended         jsonb not null default '{}'::jsonb   -- { "OE1": { "text": "...", "status": "pending" } }
);
create index responses_campaign_idx on public.responses (campaign_id);

-- ---------------------------------------------------------------- row level security
alter table public.clinics        enable row level security;
alter table public.clinic_members enable row level security;
alter table public.employees      enable row level security;
alter table public.campaigns      enable row level security;
alter table public.invitations    enable row level security;  -- no policies: service role only
alter table public.responses      enable row level security;  -- no policies: service role only

create or replace function public.cc_is_member(p_clinic uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.clinic_members m where m.clinic_id = p_clinic and m.user_id = auth.uid());
$$;

create policy clinics_member_read on public.clinics
  for select to authenticated using (public.cc_is_member(id));
create policy members_self_read on public.clinic_members
  for select to authenticated using (user_id = auth.uid());
create policy employees_member_read on public.employees
  for select to authenticated using (public.cc_is_member(clinic_id));
create policy campaigns_member_read on public.campaigns
  for select to authenticated using (public.cc_is_member(clinic_id));

-- ---------------------------------------------------------------- survey functions
-- Errors use SQLSTATE P0001 with a stable message the API maps to a page:
--   link_not_found | already_complete | survey_closed

create or replace function public.cc_create_campaign(
  p_clinic         uuid,
  p_name           text,
  p_version        text,
  p_kind           text,
  p_closes_on      date,
  p_created_by     uuid,
  p_invitation_ids uuid[],
  p_employee_ids   uuid[],
  p_token_hashes   text[],
  p_channels       text[]
) returns uuid language plpgsql security definer set search_path = public as $$
declare
  v_campaign uuid;
begin
  if coalesce(array_length(p_invitation_ids, 1), 0) < 5 then
    raise exception 'too_few_recipients';
  end if;
  if array_length(p_invitation_ids, 1) <> array_length(p_employee_ids, 1)
     or array_length(p_invitation_ids, 1) <> array_length(p_token_hashes, 1)
     or array_length(p_invitation_ids, 1) <> array_length(p_channels, 1) then
    raise exception 'mismatched_invitation_arrays';
  end if;
  if exists (
    select 1 from unnest(p_employee_ids) e(id)
    where not exists (select 1 from public.employees x where x.id = e.id and x.clinic_id = p_clinic and x.active)
  ) then
    raise exception 'employee_not_in_clinic';
  end if;

  insert into public.campaigns (clinic_id, name, instrument_version, kind, closes_on, created_by)
  values (p_clinic, p_name, p_version, p_kind, p_closes_on, p_created_by)
  returning id into v_campaign;

  insert into public.invitations (id, campaign_id, employee_id, token_hash, channel)
  select i, v_campaign, e, h, c
  from unnest(p_invitation_ids, p_employee_ids, p_token_hashes, p_channels) as t(i, e, h, c);

  return v_campaign;
end;
$$;

create or replace function public.cc_get_invitation(p_token_hash text)
returns table (
  status             text,
  draft              jsonb,
  campaign_id        uuid,
  campaign_name      text,
  campaign_status    text,
  closes_on          date,
  instrument_version text,
  kind               text,
  clinic_name        text,
  survey_intro       text,
  open_ended_mode    text,
  is_open            boolean
) language sql stable security definer set search_path = public as $$
  select i.status, i.draft, c.id, c.name, c.status, c.closes_on, c.instrument_version, c.kind,
         k.name, k.survey_intro, k.open_ended_mode,
         (c.status = 'active' and current_date <= c.closes_on)
  from public.invitations i
  join public.campaigns c on c.id = i.campaign_id
  join public.clinics k on k.id = c.clinic_id
  where i.token_hash = p_token_hash;
$$;

create or replace function public.cc_save_draft(p_token_hash text, p_draft jsonb)
returns text language plpgsql security definer set search_path = public as $$
declare
  v_inv record;
begin
  select i.id, i.status, (c.status = 'active' and current_date <= c.closes_on) as is_open
    into v_inv
  from public.invitations i join public.campaigns c on c.id = i.campaign_id
  where i.token_hash = p_token_hash
  for update of i;

  if not found then raise exception 'link_not_found'; end if;
  if v_inv.status = 'complete' then raise exception 'already_complete'; end if;
  if not v_inv.is_open then raise exception 'survey_closed'; end if;

  update public.invitations set status = 'in_progress', draft = p_draft where id = v_inv.id;
  return 'in_progress';
end;
$$;

-- Write the response, then mark the invitation complete, in one transaction.
create or replace function public.cc_submit_response(
  p_token_hash   text,
  p_demographics jsonb,
  p_answers      jsonb,
  p_open_ended   jsonb
) returns void language plpgsql security definer set search_path = public as $$
declare
  v_inv record;
begin
  select i.id, i.status, c.id as campaign_id, c.clinic_id, c.instrument_version,
         (c.status = 'active' and current_date <= c.closes_on) as is_open
    into v_inv
  from public.invitations i join public.campaigns c on c.id = i.campaign_id
  where i.token_hash = p_token_hash
  for update of i;

  if not found then raise exception 'link_not_found'; end if;
  if v_inv.status = 'complete' then raise exception 'already_complete'; end if;
  if not v_inv.is_open then raise exception 'survey_closed'; end if;

  insert into public.responses (clinic_id, campaign_id, instrument_version, demographics, answers, open_ended)
  values (v_inv.clinic_id, v_inv.campaign_id, v_inv.instrument_version,
          coalesce(p_demographics, '{}'::jsonb), coalesce(p_answers, '{}'::jsonb), coalesce(p_open_ended, '{}'::jsonb));

  update public.invitations set status = 'complete', draft = null where id = v_inv.id;
end;
$$;

-- ---------------------------------------------------------------- owner functions
-- The API checks membership before calling these.

create or replace function public.cc_campaign_counts(p_campaign uuid)
returns table (status text, channel text, n integer)
language sql stable security definer set search_path = public as $$
  select i.status, i.channel, count(*)::int
  from public.invitations i where i.campaign_id = p_campaign
  group by i.status, i.channel;
$$;

-- Answers come back only when the campaign has at least p_min responses.
-- Written answers are never returned here.
create or replace function public.cc_campaign_responses(p_campaign uuid, p_min integer default 5)
returns table (demographics jsonb, answers jsonb)
language plpgsql stable security definer set search_path = public as $$
begin
  if p_min < 5 then raise exception 'minimum_is_five'; end if;
  if (select count(*) from public.responses r where r.campaign_id = p_campaign) < p_min then
    return;
  end if;
  return query
    select r.demographics, r.answers from public.responses r
    where r.campaign_id = p_campaign
    order by random();          -- never expose storage order
end;
$$;

create or replace function public.cc_response_count(p_campaign uuid)
returns integer language sql stable security definer set search_path = public as $$
  select count(*)::int from public.responses r where r.campaign_id = p_campaign;
$$;

-- Owners see written answers only after a researcher approves them,
-- and only when the campaign has five or more responses.
create or replace function public.cc_approved_quotes(p_campaign uuid)
returns table (item_id text, body text)
language sql stable security definer set search_path = public as $$
  select q.key, q.value ->> 'text'
  from public.responses r, jsonb_each(r.open_ended) q
  where r.campaign_id = p_campaign
    and q.value ->> 'status' = 'approved'
    and (select count(*) from public.responses x where x.campaign_id = p_campaign) >= 5
  order by random();
$$;

